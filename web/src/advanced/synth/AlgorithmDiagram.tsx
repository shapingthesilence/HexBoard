export function algorithmEdges(algorithm:number){
 const row=algorithms[Math.max(0,Math.min(31,algorithm-1))],buses:number[][]=[[],[]],edges:[number,number][]=[];
 row.forEach((flags,op)=>{const input=(flags>>4)&3;if(input)for(const from of buses[input-1])edges.push([from,op]);const out=flags&3;if(out){if(!(flags&4))buses[out-1]=[];buses[out-1].push(op);}else edges.push([op,6]);if(flags&0x40)edges.push([row.findIndex(v=>!!(v&0x80)),op]);});return edges;
}
